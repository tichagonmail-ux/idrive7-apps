'use strict';
// Check actual paint calls and independently rasterized label ink. This catches
// a dial that is mathematically proportional but visually points at a neighbour.
const assert=require('assert'),path=require('path'),fs=require('fs');
const root=path.resolve(__dirname,'../../dist/dragon_super/source/javascript');
const {Canvas}=require(path.join(root,'kit/canvas')),{paint}=require(path.join(root,'dragon_gauges'));
const originalLine=Canvas.prototype.line,originalText=Canvas.prototype.text;
let lines=[],texts=[];
Canvas.prototype.line=function(...args){lines.push({canvas:this,args});return originalLine.apply(this,args);};
Canvas.prototype.text=function(...args){texts.push({canvas:this,args});return originalText.apply(this,args);};
function inkCentre(args,w,h) {
 const cv=new Canvas(w,h);originalText.apply(cv,args);
 let first=h,last=-1;
 for(let y=0;y<h;y++)for(let x=0;x<w;x++)if(cv.d[(y*w+x)*4+3]){first=Math.min(first,y);last=Math.max(last,y);}
 assert(last>=first,'label rendered no ink');return (first+last+1)/2;
}
let count=0;
for(const [signal,max,step]of [['speed',330,30],['rpm',8000,1000]])for(const [w,h]of [[600,455],[300,228]]){
 for(let value=0;value<=max;value+=step){
  lines=[];texts=[];paint({signal,max,w,h},value,null,'D4');
  const needle=lines.find(l=>l.args[5]==='#ffffff'&&Math.abs(l.args[4]-5*h/455)<1e-6);
  assert(needle,signal+' missing needle');const ny=needle.args[1];
  assert(Math.abs(ny-needle.args[3])<1e-6,'needle is not horizontal');
  const majors=lines.filter(l=>l.args[5]==='#dce9f1');const tick=majors[value/step];
  assert(Math.abs(tick.args[1]-ny)<1e-6&&Math.abs(tick.args[3]-ny)<1e-6,'needle is not on the corresponding tick');
  const label=texts.find(t=>t.args[0]===String(signal==='rpm'?value/1000:value)&&Math.abs(t.args[3]-22*h/455)<1e-6);
  assert(label,'corresponding label missing');
  assert(Math.abs(inkCentre(label.args,w,h)-ny)<=1.25,signal+' '+value+' actual digit ink is off its tick');
  const readout=texts.find(t=>t.args[5]&&t.args[5].font==='num');assert.equal(readout.args[0],String(value));
  if(value>0){
   const fills=lines.filter(l=>l.args[5]===(signal==='rpm'?'#ff3a4e':'#42cfff')&&Math.abs(l.args[4]-17*h/455)<1e-6);
   assert(fills.length);const last=fills[fills.length-1];assert(Math.abs(last.args[3]-ny)<1e-6,'bar segment overshot its value');
   // The rasterized progress layer must have no pixels above its needle row.
   const pixels=last.canvas.d;
   for(let y=0;y<Math.ceil(ny);y++)for(let x=0;x<w;x++)assert.equal(pixels[(y*w+x)*4+3],0,'rounded fill cap leads the needle');
  }
  count++;
 }
}
for(const [signal,max,step,value]of [['speed',330,30,63],['rpm',8000,1000,1139]]){
 lines=[];texts=[];paint({signal,max,w:600,h:455},value,null,'D7');
 const needle=lines.find(l=>l.args[5]==='#ffffff'&&l.args[4]===5);
 const low=Math.floor(value/step)*step,high=low+step;
 const centre=n=>{
  const t=texts.find(t=>t.args[0]===String(signal==='rpm'?n/1000:n)&&t.args[3]===22);
  assert(t);return inkCentre(t.args,600,455);
 };
 const a=centre(low),b=centre(high),expected=a+(b-a)*(value-low)/step;
 assert(Math.abs(needle.args[1]-expected)<=1.5,signal+' between-tick value is visually misplaced');
 assert.equal(texts.find(t=>t.args[5]&&t.args[5].font==='num').args[0],String(value));
}
for(const [signal,max]of [['speed',330],['rpm',8000]]){
 lines=[];texts=[];paint({signal,max,w:600,h:455},NaN,null,'D4');
 assert(!lines.some(l=>l.args[5]==='#ffffff'&&l.args[4]===5),'missing data drew a zero needle');
 assert(texts.some(t=>t.args[0]==='--'&&t.args[5]&&t.args[5].font==='num'));
}
// Reproducible inspection examples, generated by the same actual paint code.
for(const [signal,max,value]of [['speed',330,60],['speed',330,90],['rpm',8000,1000],['rpm',8000,2000]]){
 const px=paint({signal,max,w:600,h:455},value,null,'D4');const cv=new Canvas(600,455);cv.d.set(px);
 fs.writeFileSync(path.resolve(__dirname,'../../dist/gauge-'+signal+'-'+value+'.png'),cv.png());
}
Canvas.prototype.line=originalLine;Canvas.prototype.text=originalText;
console.log('PASS '+count+' major dial cases plus 63 km/h and 1139 RPM between ticks: actual label ink, tick and needle align; fill ends exactly; missing data stays unknown');
